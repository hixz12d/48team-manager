// Optional Team48 handoff: sync the team, link the member, authorize, push and count.
const TEAM48 = (() => {
  try {
    const config = PRIVATE_CONFIG.TEAM48;
    const url = new URL(config.baseUrl);
    const local = url.protocol === 'http:' && ['127.0.0.1', 'localhost'].includes(url.hostname);
    return (url.protocol === 'https:' || local) && typeof config.token === 'string' && config.token.length >= 24 ?
      {origin: url.origin, token: config.token} : null;
  } catch { return null; }
})();
async function team48(path, body) {
  if (!TEAM48) throw new Error('插件未配置 Team48 地址和令牌，请用 --team48-token 重新打包。');
  let response;
  try {
    response = await fetch(TEAM48.origin + path, {
      method: body ? 'POST' : 'GET', credentials: 'omit', cache: 'no-store', signal: AbortSignal.timeout(90000),
      headers: {Authorization: `Bearer ${TEAM48.token}`, Accept: 'application/json', ...(body ? {'Content-Type': 'application/json'} : {})},
      body: body ? JSON.stringify(body) : undefined,
    });
  } catch { throw new Error('无法连接 Team48，请检查网络后重试。'); }
  if (response.status === 401) throw new Error('Team48 拒绝了插件令牌，请核对 EXTENSION_API_TOKEN 后重新打包。');
  if (response.status === 404) throw new Error('Team48 未启用插件接口，请在服务器配置 EXTENSION_API_TOKEN 并更新版本。');
  if (!response.ok) throw new Error(`Team48 返回 HTTP ${response.status}，请稍后重试。`);
  return response.json();
}

// ---- Phone relay: numbers and SMS codes come from Team48's phone pool (docs/contracts/phone-relay.md). ----
// Only for auto/review jobs of a package with a Team48 token, or server jobs whose task allowed the pool.
// The full number stays in the job and the page; status text shows its last 4 digits only.
const PHONE_TRIES = 3, SMS_WAIT = 90000, SMS_POLL = 5000;
const PHONE_REASONS = {invalid: '不被 OpenAI 接受', recently_used: '刚被用过', risk: '收不到短信或被切到 WhatsApp',
  no_sms: '90 秒内没收到短信', wrong_code: '短信验证码被拒', lease_lost: '已不在本任务名下', cancelled: '提交后页面没有反应'};
let phoneCalls = 0; // relay requests in flight; a new number is only requested when none is
const phoneRelayEnabled = job => !!job && !job.phoneRelayOff && ['auto', 'review'].includes(job.mode || 'auto') &&
  (RUNNER && job.runner ? job.runner.phonePool === true : !RUNNER && !!TEAM48);
const phoneContext = job => ({id: job.id, session: job.id.replace(/-/g, '').toLowerCase(), email: job.email,
  workspaceId: Number(job.autoHandoff?.workspaceId || job.handoff?.workspaceId) || 0, phase: job.phase === 'oauth' ? 'oauth' : 'signup'});
// Server text for the status line: never a link or a long digit run.
const relayText = value => String(value || '').replace(/https?:\/\/\S+/g, '[链接]').replace(/\+?\d[\d\s()-]{6,}\d/g, '***').slice(0, 150);
async function phoneRelay(context, body) {
  const payload = {...body, phase: context.phase};
  if (RUNNER) return runner ? runner.phone(payload) : {ok: false, network: true, message: '服务器模式尚未就绪。'};
  if (!TEAM48) return {ok: false, error_code: 'phone_relay_disabled', message: '插件未配置 Team48 令牌。'};
  Object.assign(payload, {session: context.session, email: context.email, ...(context.workspaceId > 0 ? {workspaceId: context.workspaceId} : {})});
  let response;
  try {
    response = await fetch(TEAM48.origin + '/api/ext/phone', {
      method: 'POST', credentials: 'omit', cache: 'no-store', signal: AbortSignal.timeout(30000),
      headers: {Authorization: `Bearer ${TEAM48.token}`, Accept: 'application/json', 'Content-Type': 'application/json'},
      body: JSON.stringify(payload),
    });
  } catch { return {ok: false, network: true, message: '无法连接 Team48 接码接口。'}; }
  if (response.status >= 500) return {ok: false, network: true, message: `Team48 接码接口返回 HTTP ${response.status}。`};
  let data = null;
  try { data = await response.json(); } catch { /* not JSON */ }
  if (response.ok && data && typeof data === 'object' && typeof data.ok === 'boolean') return data;
  const message = response.status === 401 ? 'Team48 拒绝了插件令牌，请核对后重新打包。' :
    response.status === 404 ? 'Team48 未启用接码接口，请更新服务器版本。' : `Team48 接码接口返回 HTTP ${response.status}。`;
  return {ok: false, error_code: 'invalid_request', message};
}
// report / release: the result is ignored (the server lock expires by itself).
function firePhoneCall(context, body) {
  phoneCalls++;
  phoneRelay(context, body).catch(() => {}).finally(() => { phoneCalls = Math.max(0, phoneCalls - 1); });
}
function resetPhoneSteps(job) {
  // Every number is a fresh submission of the same page: drop the old claims for the phone steps.
  for (const bag of [job.claims, job.continueClicks, job.clickReservations, job.reviewSteps]) {
    for (const key of Object.keys(bag || {})) if (/^phone(_otp)?:/.test(key)) delete bag[key];
  }
  if (job.attempts) { delete job.attempts.phone; delete job.attempts.phone_otp; }
  if (/^phone(_otp)?:/.test(job.retryClaim || '')) delete job.retryClaim;
}
const phoneLimit = job => job.phoneLimit || PHONE_TRIES;
function phoneLimitPause(job) {
  pauseJob(job, `已连续 ${job.phoneTries || 0} 个号失败，可能是账号或代理被风控，请人工处理。`, 'phone_limit');
}
// Drops the current number after a failure: report it (unless the lease is already gone), then go back and
// take the next one, or pause once the tries are used up.
function failPhone(job, outcome) {
  const phone = job.phone;
  if (!phone) return;
  const context = phoneContext(job);
  delete job.phone;
  resetPhoneSteps(job);
  if (!phone.bound && outcome !== 'lease_lost') (job.phoneFailedIds ||= []).push(phone.id);
  job.phoneBack = true;
  recordEvent(job, 'phone_rejected', {stage: job.stage, outcome: PHONE_OUTCOMES.has(outcome) ? outcome : undefined});
  if (outcome !== 'lease_lost') firePhoneCall(context, {action: 'report', phoneId: phone.id, bound: phone.bound, outcome});
  if (phone.bound) {
    // The account's own number cannot be swapped for another one.
    delete job.phoneBack;
    pauseJob(job, `账号已绑定的尾号 ${phone.tail} 号码${PHONE_REASONS[outcome] || '不可用'}，请人工处理后点继续。`, 'phone_relay_error');
    return;
  }
  if ((job.phoneTries || 0) >= phoneLimit(job)) { phoneLimitPause(job); return; }
  job.message = `尾号 ${phone.tail} 的号码${PHONE_REASONS[outcome] || '不可用'}，正在换号（已用 ${job.phoneTries || 0}/${phoneLimit(job)} 个）`;
}
// The page left the phone steps after the SMS code was submitted.
function phoneSucceeded(job) {
  const phone = job.phone;
  if (!phone?.code && !phone?.codeSubmittedAt) return false;
  const context = phoneContext(job);
  delete job.phone; delete job.phoneBack;
  resetPhoneSteps(job);
  job.phoneSuccess = true;
  firePhoneCall(context, {action: 'report', phoneId: phone.id, bound: phone.bound, outcome: 'success'});
  return true;
}
// Stop, timeout or closed tab: free the number at once instead of waiting for the lock to expire.
function releasePhone(job) {
  delete job.phoneBack;
  if (!job.phone) return;
  const context = phoneContext(job);
  delete job.phone;
  if (!RUNNER) firePhoneCall(context, {action: 'release'}); // the server releases a run's numbers itself
}
const phoneReply = phone => ({id: phone.id, number: phone.number, national: phone.number.replace(/\D/g, '').slice(-10), tail: phone.tail, bound: phone.bound});
// Runs outside the job queue (like finishCodePoll); only the result is stored under it.
async function finishPhoneCall(call) {
  let result;
  try {
    const body = call.action === 'acquire' ? {action: 'acquire', bound: call.bound} : {action: 'code', phoneId: call.phoneId, bound: call.bound};
    for (let attempt = 0; ; attempt++) {
      result = await phoneRelay(call, body);
      if (call.action !== 'acquire' || !result?.network || attempt >= 2) break;
      await sleep(3000);
    }
    // A report that never reached the server leaves the failed number locked to this session.
    if (call.action === 'acquire' && !call.bound && result?.ok && call.failedIds.includes(Number(result.phoneId))) {
      await phoneRelay(call, {action: 'release'});
      result = await phoneRelay(call, body);
      if (result?.ok && call.failedIds.includes(Number(result.phoneId))) {
        // The pool has nothing this account has not tried yet.
        await phoneRelay(call, {action: 'release'});
        result = {ok: false, error_code: 'phone_pool_empty', message: '号码池里没有本账号还没试过的号。'};
      }
    }
  } catch { result = {ok: false, network: true, message: '接码请求失败。'}; }
  finally { phoneCalls = Math.max(0, phoneCalls - 1); }
  return serial(async () => {
    const job = await loadJob();
    if (!job || job.id !== call.id) return {};
    return call.action === 'acquire' ? applyAcquire(job, call, result) : applyCode(job, call, result);
  });
}
async function applyAcquire(job, call, result) {
  const number = String(result?.number || '');
  if (result?.ok && (call.bound ? /^\+?\d{6,15}$/.test(number) : /^\+1\d{10}$/.test(number)) && Number.isInteger(Number(result.phoneId))) {
    const phone = {id: Number(result.phoneId), number, bound: call.bound, tail: number.slice(-4), acquiredAt: Date.now(),
      submittedAt: call.bound ? Date.now() : 0, codeSubmittedAt: 0, lastPoll: 0};
    if (!ACTIVE.has(job.status)) {
      firePhoneCall(call, {action: 'report', phoneId: phone.id, bound: phone.bound, outcome: 'cancelled'});
      return {};
    }
    if (job.phone && job.phone.id !== phone.id) {
      firePhoneCall(call, {action: 'report', phoneId: job.phone.id, bound: job.phone.bound, outcome: 'cancelled'});
    }
    job.phone = phone;
    job.phoneTries = (job.phoneTries || 0) + 1;
    resetPhoneSteps(job);
    recordEvent(job, 'phone_acquired', {stage: job.stage});
    job.message = call.bound ? `页面要求验证已绑定的尾号 ${phone.tail} 号码，等待短信验证码` :
      `已领取尾号 ${phone.tail} 的号码，正在填写（第 ${job.phoneTries}/${phoneLimit(job)} 个）`;
    await saveJob(job);
    return job.status === 'running' ? phoneReply(phone) : {};
  }
  if (result?.ok) {
    // Not a +1 number: the page could not take it as is.
    firePhoneCall(call, {action: 'report', phoneId: Number(result.phoneId) || 0, bound: call.bound, outcome: 'cancelled'});
    result = {ok: false, message: '服务器下发的号码不是 +1 美国号。'};
  }
  if (job.status !== 'running' || result?.error_code === 'run_gone') return {};
  const code = result?.error_code;
  if (code === 'phone_pool_empty') pauseJob(job, '号码池没有可用号，去 Team48 资源页导入后点继续。', 'phone_pool_empty');
  else if (code === 'phone_relay_disabled') {
    // Same as a package without relay: stop at the phone page like before.
    job.phoneRelayOff = true;
    pauseJob(job, job.phase === 'oauth' ? '授权要求手机验证，请在网页手动完成；完成后插件会自动提交回调。' : '注册需要手机验证，请在网页手动完成后继续。', 'phone');
  } else pauseJob(job, `接码失败：${relayText(result?.message) || '服务器没有返回号码'}。请处理后点继续。`, 'phone_relay_error');
  await saveJob(job);
  return {paused: true};
}
async function applyCode(job, call, result) {
  const phone = job.phone;
  if (!ACTIVE.has(job.status) || phone?.id !== call.phoneId || phone.bound !== call.bound) return {code: null};
  if (result?.ok === false && result.error_code === 'lease_lost') {
    // While paused, the next poll after Continue gets the same answer.
    if (job.status !== 'running') return {code: null};
    failPhone(job, 'lease_lost');
    await saveJob(job);
    return {rejected: true};
  }
  const code = result?.ok ? String(result.code || '') : '';
  if (!/^\d{6}$/.test(code) || phone.codeSubmittedAt) return {code: null};
  if (!phone.code) {
    phone.code = code;
    recordEvent(job, 'sms_received', {stage: 'phone_otp'});
    if (job.status === 'running') job.message = '已收到短信验证码，正在逐位输入';
    await saveJob(job);
  }
  return job.status === 'running' ? {code: phone.code} : {code: null};
}

