// ---- Server mode (only with a valid RUNNER export; see runner.mjs) ----
// The server browser opens about:blank in a normal window of a fresh, dedicated profile.
async function pickRunnerTab() {
  const windows = await chrome.windows.getAll({populate: true, windowTypes: ['normal']});
  const window = windows.find(item => !item.incognito && item.tabs?.length);
  return window?.tabs.find(item => item.active) || window?.tabs[0] || chrome.tabs.create({url: 'about:blank', active: true});
}
if (RUNNER) {
  runner = createRunner(RUNNER, {
    ready,
    version: () => chrome.runtime.getManifest().version,
    pickTab: pickRunnerTab,
    loadJob,
    startJob: ({email, password, profile, workspaceNames, phonePool}) => serial(async () => {
      const tab = await pickRunnerTab();
      await startJob({email, mode: 'auto', profile, hidePanel: true, handoff: null, tabId: tab.id, password,
        runner: {workspaceNames, phonePool: phonePool === true}});
    }),
    stopJob: () => serial(async () => {
      const job = await loadJob();
      if (!job?.runner || job.status === 'stopped' || job.handoff?.status === 'done') return;
      applyStop(job);
      await saveJob(job);
    }),
    // Opens the server's authorization link in the signup tab; a repeated link is ignored.
    // url === null resumes an "opening" step interrupted by a worker restart.
    authorize: async url => {
      const id = await serial(async () => {
        const job = await loadJob();
        if (!job?.runner) return null;
        if (url && !job.handoff && job.status === 'done' && job.phase !== 'oauth') {
          const names = job.runner.workspaceNames || [];
          job.handoff = {status: 'opening', authorizeUrl: url, workspaceNames: names, workspaceName: String(names[0] || '').slice(0, 120),
            startedAt: Date.now(), message: '已收到授权链接，正在打开授权页面'};
          await saveJob(job);
        }
        return job.handoff?.status === 'opening' ? job.id : null;
      });
      if (id) await openAuthorization(id);
    },
    callbackResult: (ok, message) => serial(async () => {
      const job = await loadJob();
      if (!job?.runner || job.handoff?.status !== 'completing') return;
      if (ok) {
        Object.assign(job.handoff, {status: 'done', message: '授权回调已交给服务器'});
        delete job.handoff.authorizeUrl; delete job.handoff.callbackUrl;
        if (job.codexResult !== 'phone_required') job.codexResult = 'no_phone';
        job.message = '已把授权回调交给服务器。';
      } else failHandoff(job, message);
      await saveJob(job);
    }),
  });
  chrome.runtime.onStartup.addListener(() => { runner.boot(); });
  chrome.runtime.onInstalled.addListener(() => { runner.boot(); });
  // Also on every worker start, so a suspended worker resumes reporting right away.
  runner.boot();
}
